#!/usr/bin/env python3
"""Generate vst/params.json and src/params_gen.h from variant_spec.py (run from anywhere)."""
import json, os
import variant_spec as S
ROOT=os.path.join(os.path.dirname(os.path.abspath(__file__)),"..")
def main():
    out=[]
    for p in S.P:
        d={"key":p["key"],"name":p["name"]}
        if p["opts"]: d["options"]=p["opts"]; d["default"]=p["default"]
        elif p["kind"]!="str" and p["kind"]!="mom": d["min"]=p["min"]; d["max"]=p["max"]; d["default"]=p["default"]
        if p["kind"]=="mom": d["min"]=0; d["max"]=1; d["default"]=0; d["momentary"]=True
        if p["kind"]=="str": d["display"]="string"; d["type"]="readout"
        elif p["display"]: d["display"]=p["display"]
        if p.get("unit"): d["unit"]=p["unit"]
        if "step_of" in p: d["step_of"]=p["step_of"]; d["step_delta"]=p["step_delta"]
        if "poll" in p: d["poll"]=p["poll"]
        out.append(d)
    json.dump({"name":"VARIANT","params":out},open(os.path.join(ROOT,"vst","params.json"),"w"),indent=1)
    h=["/* generated by tools/gen_params.py from tools/variant_spec.py: do not edit */","#pragma once",
       "typedef struct { const char *key; float min, max, def; int nopts, kind; } vpdef_t; /* kind: 0 value, 1 option, 2 momentary, 3 text */",
       "enum {"]
    h+=["  P_%s,"%p["key"] for p in S.P]; h.append("  NPAR };")
    h.append("static const vpdef_t VPD[NPAR] = {")
    for p in S.P:
        k={"val":0,"opt":1,"mom":2,"str":3}[p["kind"]]
        n=len(p["opts"]) if p["opts"] else 0
        mn,mx,df=(0,max(0,n-1),p["default"]) if n else (p["min"],p["max"],p["default"])
        if p["kind"] in ("mom","str"): mn,mx,df=0,1,0
        h.append('  {"%s", %g, %g, %g, %d, %d},'%(p["key"],mn,mx,df,n,k))
    h.append("};")
    h.append("static const int SCALE_N[%d] = {%s};"%(len(S.SCALES),", ".join(str(len(s[1])) for s in S.SCALES)))
    h.append("static const unsigned char SCALE_IV[%d][12] = {"%len(S.SCALES))
    for n,iv in S.SCALES: h.append("  {%s}, /* %s */"%(", ".join(str(x) for x in iv+[0]*(12-len(iv))),n))
    h.append("};")
    h.append("static const char *const SCALE_NAME[%d] = {%s};"%(len(S.SCALES),", ".join('"%s"'%s[0] for s in S.SCALES)))
    h.append("static const char *const ROOT_NAME[12] = {%s};"%", ".join('"%s"'%r for r in S.ROOTS))
    h.append("static const char *const RATE_NAME[%d] = {%s};"%(len(S.RATES),", ".join('"%s"'%r[0] for r in S.RATES)))
    h.append("static const double RATE_BEATS[%d] = {%s};"%(len(S.RATES),", ".join(repr(r[1]) for r in S.RATES)))
    h.append("static const int EVERY_BARS[%d] = {%s};"%(len(S.EVERY),", ".join(str(e[1]) for e in S.EVERY)))
    open(os.path.join(ROOT,"src","params_gen.h"),"w").write("\n".join(h)+"\n")
    print(len(S.P),"params")
if __name__=="__main__": main()
